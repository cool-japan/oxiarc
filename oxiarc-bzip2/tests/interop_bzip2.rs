#[test]
fn decodes_multistream_real_cli_fixture() {
    // Two real bzip2 CLI streams at different levels: both must decode,
    // in order, exactly as `bzip2 -d` does.
    let mut expected = multistream_a();
    expected.extend_from_slice(&multistream_b());
    let decoded = decompress(MULTISTREAM_A9_B1).expect("decode two-stream fixture");
    assert_eq!(decoded, expected);
}

#[test]
fn decodes_multistream_with_empty_middle_stream() {
    let mut expected = multistream_a();
    expected.extend_from_slice(&multistream_b());
    let decoded = decompress(MULTISTREAM_A9_EMPTY_B1).expect("decode three-stream fixture");
    assert_eq!(decoded, expected);
}

#[test]
fn multistream_first_stream_only_is_data_loss_no_more() {
    // Regression guard for the original bug: the fixture holds strictly
    // more data than its first stream alone.
    let first_only = multistream_a();
    let decoded = decompress(MULTISTREAM_A9_B1).expect("decode two-stream fixture");
    assert!(decoded.len() > first_only.len());
    assert_eq!(&decoded[..first_only.len()], &first_only[..]);
}

#[test]
fn multistream_with_corrupted_second_stream_is_error() {
    // Corruption in the *second* stream must fail the whole decode.
    let mut corrupted = MULTISTREAM_A9_B1.to_vec();
    let last = corrupted.len() - 20;
    corrupted[last] ^= 0x40;
    assert!(decompress(&corrupted[..]).is_err());
}

#[test]
fn multistream_truncated_second_header_is_error() {
    // Chop the concatenation inside the second stream's 4-byte header:
    // that is a truncated stream, not a clean end of input.
    let first_len = 122; // length of the level-9 first member (see fixture provenance)
    let truncated = &MULTISTREAM_A9_B1[..first_len + 2];
    assert!(decompress(truncated).is_err());
}

#[test]
fn trailing_zero_padding_is_error_not_silent() {
    // Unlike `bzip2 -d` (which warns), a library must not silently ignore
    // trailing bytes: report them so callers can decide.
    let mut padded = multistream_fixture_first_member();
    padded.extend_from_slice(&[0u8; 8]);
    assert!(decompress(&padded[..]).is_err());
}

/// The first member of the two-stream fixture (a complete stream).
fn multistream_fixture_first_member() -> Vec<u8> {
    MULTISTREAM_A9_B1[..122].to_vec()
}

