// ---------------------------------------------------------------------------
// Output-size limit (decompression-bomb guard)
// ---------------------------------------------------------------------------

#[test]
fn decompress_with_limit_accepts_within_budget() {
    let data = text_data(60_000);
    let compressed = compress(&data, CompressionLevel::new(1)).expect("compress");
    let decoded = decompress_with_limit(&compressed[..], 60_000).expect("decode under limit");
    assert_eq!(decoded, data);
}

#[test]
fn decompress_with_limit_rejects_over_budget() {
    let data = text_data(60_000);
    let compressed = compress(&data, CompressionLevel::new(1)).expect("compress");
    assert!(decompress_with_limit(&compressed[..], 59_999).is_err());
}

#[test]
fn decompress_with_limit_is_cumulative_across_blocks() {
    // This real libbz2 level-9 fixture contains 1.2 MB of decoded data, so it
    // crosses the format's 900 KB block boundary within one BZip2 stream.
    let expected = text_data(1_200_000);

    let decoded = decompress_with_limit(PY_TEXT1M2_L9, expected.len())
        .expect("exact cumulative limit should accept multi-block stream");
    assert_eq!(decoded, expected);

    assert!(
        decompress_with_limit(PY_TEXT1M2_L9, expected.len() - 1).is_err(),
        "one byte below the cumulative multi-block output must be rejected"
    );
}

#[test]
fn multistream_every_truncation_errs_or_is_a_stream_boundary() {
    // Truncating the two-stream fixture at any point must never panic and
    // may only succeed at exact stream boundaries (first member: 122
    // bytes; whole fixture). Everything else is corruption.
    let first = multistream_a();
    let mut both = first.clone();
    both.extend_from_slice(&multistream_b());
    for len in 0..MULTISTREAM_A9_B1.len() {
        match decompress(&MULTISTREAM_A9_B1[..len]) {
            Ok(out) if len == 122 => assert_eq!(out, first),
            Ok(out) => panic!("prefix of {len} bytes decoded Ok ({} bytes out)", out.len()),
            Err(_) => {}
        }
    }
    assert_eq!(decompress(MULTISTREAM_A9_B1).expect("full fixture"), both);
}

#[test]
fn multistream_bit_corruptions_never_panic() {
    // Deterministic xorshift-driven single-byte corruptions across the
    // multi-stream fixture: decode must return (Ok or Err), never panic.
    let mut state: u32 = 0x1234_5678;
    let mut next = move || {
        state ^= state << 13;
        state ^= state >> 17;
        state ^= state << 5;
        state
    };
    for _ in 0..500 {
        let mut mutated = MULTISTREAM_A9_B1.to_vec();
        let pos = next() as usize % mutated.len();
        let bit = 1u8 << (next() % 8);
        mutated[pos] ^= bit;
        let _ = decompress(&mutated[..]);
    }
}

#[test]
fn decompress_with_limit_spans_multistream() {
    // The cap applies across concatenated streams, not per stream.
    let total = multistream_a().len() + multistream_b().len();
    let decoded =
        decompress_with_limit(MULTISTREAM_A9_B1, total).expect("decode multi-stream under limit");
    assert_eq!(decoded.len(), total);
    assert!(decompress_with_limit(MULTISTREAM_A9_B1, total - 1).is_err());
}
