/// `text`: a short English sentence with one internal repeat.
fn payload_text() -> Vec<u8> {
    b"the quick brown fox jumps over the lazy dog, the quick brown fox".to_vec()
}

/// `runs`: 5000 identical bytes — drives the longest matches and, in `-lh3-`,
/// the degenerate single-symbol tables.
fn payload_runs() -> Vec<u8> {
    std::iter::repeat_n(b'#', 5000).collect()
}

/// `ramp`: every byte value cycled to 30 KB — exercises a full literal
/// alphabet plus distances spanning many `-lh2-` position groups.
fn payload_ramp() -> Vec<u8> {
    (0..=255u8).cycle().take(30_000).collect()
}

/// `longmatch`: a 300-byte pattern repeated three times, so matches exceed the
/// 31-byte direct length codes and use the eight-bit escape.
fn payload_longmatch() -> Vec<u8> {
    let base: Vec<u8> = (0..300u32).map(|i| (i % 251) as u8).collect();
    let mut data = base.clone();
    data.extend(base.iter());
    data.extend(base.iter());
    data
}

/// `repeat`: 900 copies of one line — a realistic highly-redundant text file
/// larger than the 8 KiB window.
fn payload_repeat() -> Vec<u8> {
    let unit = b"OxiArc legacy LZH exercise line.\n";
    std::iter::repeat_n(unit, 900).flatten().copied().collect()
}

