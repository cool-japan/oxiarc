//! Reference-verified `-lh2-` / `-lh3-` conformance vectors.
//!
//! # Why these exist
//!
//! Lhasa — the `lha` binary this workspace uses as an LZH oracle — implements
//! no `-lh2-` or `-lh3-` decoder at all: its decoder table
//! (`lib/lha_decoder.c`) registers `-lz4-`, `-lz5-`, `-lzs-`, `-lh0-`,
//! `-lh1-`, `-lh4-`..`-lh7-`, `-lhx-`, `-lk7-`, `-pm0-`..`-pm2-`, and there is
//! no `lh2_decoder.c`/`lh3_decoder.c` in its source tree. `delharc`, the other
//! widely-used third-party LZH decoder, does not implement them either. So
//! unlike every other method in this crate, `-lh2-`/`-lh3-` have **no oracle
//! that can be shelled out to from a test**.
//!
//! Conformance was therefore established out of band, against the canonical
//! *LHa for UNIX* decode path (`dhuf.c` for `-lh2-`, `shuf.c` for `-lh3-`,
//! plus `bitio.c`, `maketbl.c` and the `decode()` loop of `slide.c`) compiled
//! standalone and driven with the streams this crate's encoders produce. Ten
//! payloads x two methods = 20 streams decoded byte-identically through that
//! reference. The five payloads below are the subset frozen here, so the
//! in-repo gate stays hermetic and pure Rust while still asserting exactly the
//! bytes an independent LHa implementation accepted.
//!
//! # Maintaining these vectors
//!
//! The assertions are deliberately two-directional:
//!
//! * `decode_lhN(VECTOR) == payload` — the decoder agrees with the reference
//!   on bytes the reference produced. This is the direction that must never
//!   change: it is the format itself.
//! * `encode_lhN(payload) == VECTOR` — the encoder still emits exactly the
//!   stream that was validated. A deliberate encoder improvement (a better
//!   match finder, different block sizing) will fail this half; that is the
//!   intended signal. Re-run the standalone reference harness against the new
//!   output and refresh the constants — do not simply delete the assertion,
//!   because it is the only thing tying the encoder to an external
//!   implementation.

