/// `-lh2-`'s position tree grows by one 64-distance group every time the output
/// passes another 64-byte boundary, and the growth check runs at one exact
/// point in the bit stream — immediately before a position code, with the
/// output length taken *before* the current match. Encoder and decoder must
/// agree on that point to the byte: one off-by-one and the two sides use
/// differently-shaped trees from there on, producing a stream that still
/// round-trips against itself and is unreadable by a real LHa.
///
/// Self-round-trip therefore cannot catch this class of bug at all, which is
/// why the sweep below exists as a *permanent* check rather than a one-off:
/// every payload here places its first match at a chosen output offset
/// straddling 64, 128, 192, 256 and the 8192 dictionary limit, plus strides
/// that re-trigger growth continuously mid-stream.
///
/// All 26 payloads x 2 methods = 52 streams were confirmed byte-identical
/// through the standalone canonical LHa reference decoder; this test re-asserts
/// the self-consistency half hermetically.
#[test]
fn lh2_and_lh3_survive_the_position_group_boundaries() {
    /// A payload whose first match begins at exactly output offset `offset`.
    fn first_match_at(offset: usize) -> Vec<u8> {
        let mut data: Vec<u8> = (0..offset)
            .map(|i| (i.wrapping_mul(97) % 251) as u8)
            .collect();
        let head: Vec<u8> = data.iter().take(32).copied().collect();
        for _ in 0..6 {
            data.extend(head.iter());
        }
        data
    }

    let mut payloads: Vec<(String, Vec<u8>)> = Vec::new();
    for offset in [
        60usize, 61, 62, 63, 64, 65, 66, 67, 68, 127, 128, 129, 130, 191, 192, 193, 255, 256, 257,
        8190, 8191, 8192, 8193,
    ] {
        payloads.push((format!("first_match_at_{offset}"), first_match_at(offset)));
    }
    // Strides that keep re-triggering growth for the whole stream.
    for stride in [63usize, 64, 65] {
        let unit: Vec<u8> = (0..stride)
            .map(|i| (i.wrapping_mul(31) % 253) as u8)
            .collect();
        let data: Vec<u8> = std::iter::repeat_n(unit.as_slice(), 400)
            .flatten()
            .copied()
            .collect();
        payloads.push((format!("stride_{stride}"), data));
    }

    for (label, data) in payloads {
        let lh2 = encode_lh2(&data).unwrap_or_else(|e| panic!("[{label}] encode -lh2-: {e}"));
        assert_eq!(
            decode_lh2(&lh2, data.len() as u64).unwrap_or_else(|e| panic!("[{label}] decode: {e}")),
            data,
            "[{label}] -lh2- must round-trip across a position-group boundary"
        );
        let lh3 = encode_lh3(&data).unwrap_or_else(|e| panic!("[{label}] encode -lh3-: {e}"));
        assert_eq!(
            decode_lh3(&lh3, data.len() as u64).unwrap_or_else(|e| panic!("[{label}] decode: {e}")),
            data,
            "[{label}] -lh3- must round-trip across a position-group boundary"
        );
    }
}
