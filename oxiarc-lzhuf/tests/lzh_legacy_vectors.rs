/// Assert both directions for one payload/method pair.
fn check(label: &str, payload: &[u8], vector: &[u8], method: LzhMethod) {
    let decoded = match method {
        LzhMethod::Lh2 => decode_lh2(vector, payload.len() as u64),
        LzhMethod::Lh3 => decode_lh3(vector, payload.len() as u64),
        other => panic!("unexpected method {other}"),
    }
    .unwrap_or_else(|e| panic!("[{label}] decoding the reference-verified vector failed: {e}"));
    assert_eq!(
        decoded, payload,
        "[{label}] decoder disagrees with the reference-accepted stream"
    );

    let encoded = match method {
        LzhMethod::Lh2 => encode_lh2(payload),
        LzhMethod::Lh3 => encode_lh3(payload),
        other => panic!("unexpected method {other}"),
    }
    .unwrap_or_else(|e| panic!("[{label}] encoding failed: {e}"));
    assert_eq!(
        encoded, vector,
        "[{label}] encoder no longer emits the stream the reference validated \
         (see this file's header for how to refresh the vectors)"
    );

    // The public method-dispatched entry points must agree with the direct
    // codec functions, so archive readers get the same bytes.
    let via_dispatch = decode_lzh(vector, method, payload.len() as u64)
        .unwrap_or_else(|e| panic!("[{label}] decode_lzh dispatch failed: {e}"));
    assert_eq!(via_dispatch, payload, "[{label}] decode_lzh dispatch");
}

