/// Read every entry of a fixture into `decoded name -> content`, asserting
/// that no two entries collapse onto the same decoded name.
fn extract_all(fixture: &[u8]) -> HashMap<String, Vec<u8>> {
    let mut reader = ZipReader::new(Cursor::new(fixture)).expect("fixture must parse");
    let entries = reader.entries().to_vec();
    let mut extracted = HashMap::new();
    for entry in &entries {
        let data = reader.extract(entry).expect("extraction must succeed");
        let previous = extracted.insert(entry.name.clone(), data);
        assert!(
            previous.is_none(),
            "decoded entry name {:?} collided — extraction would overwrite a file",
            entry.name
        );
    }
    extracted
}

#[test]
fn sjis_names_without_efs_decode_distinct_and_extract_all_files() {
    let files = extract_all(ZIP_SJIS_NO_EFS);
    assert_eq!(files.len(), 2, "both entries must survive extraction");
    assert_eq!(
        files.get("あ.txt").map(Vec::as_slice),
        Some(b"HIRAGANA-A".as_slice())
    );
    assert_eq!(
        files.get("い.txt").map(Vec::as_slice),
        Some(b"HIRAGANA-I".as_slice())
    );
}

#[test]
fn sjis_fixture_exposes_raw_name_bytes() {
    let reader = ZipReader::new(Cursor::new(ZIP_SJIS_NO_EFS)).expect("fixture must parse");
    assert_eq!(reader.entries().len(), 2);
    assert_eq!(
        reader.entry_name_bytes(0),
        Some([0x82, 0xA0, b'.', b't', b'x', b't'].as_slice())
    );
    assert_eq!(
        reader.entry_name_bytes(1),
        Some([0x82, 0xA2, b'.', b't', b'x', b't'].as_slice())
    );
    assert_eq!(reader.entry_name_bytes(2), None);
}

#[test]
fn efs_utf8_japanese_names_decode_and_extract_all_files() {
    let files = extract_all(ZIP_EFS_UTF8);
    assert_eq!(files.len(), 2, "both entries must survive extraction");
    assert_eq!(
        files.get("日本語.txt").map(Vec::as_slice),
        Some(b"NIHONGO".as_slice())
    );
    assert_eq!(
        files.get("かな.txt").map(Vec::as_slice),
        Some(b"KANA".as_slice())
    );

    let reader = ZipReader::new(Cursor::new(ZIP_EFS_UTF8)).expect("fixture must parse");
    assert_eq!(reader.entry_name_bytes(0), Some("日本語.txt".as_bytes()));
    assert_eq!(reader.entry_name_bytes(1), Some("かな.txt".as_bytes()));
}

#[test]
fn cp437_legacy_names_decode_injectively_and_extract_all_files() {
    let files = extract_all(ZIP_CP437_LEGACY);
    assert_eq!(files.len(), 2, "both entries must survive extraction");
    // CP437: 0x81 -> 'ü', 0x82 -> 'é' (same view python's cp437 codec and
    // the legacy `zip` crate produce for these archives).
    assert_eq!(
        files.get("ü a.txt").map(Vec::as_slice),
        Some(b"LEGACY-X".as_slice())
    );
    assert_eq!(
        files.get("é a.txt").map(Vec::as_slice),
        Some(b"LEGACY-Y".as_slice())
    );
    for name in files.keys() {
        assert!(
            !name.contains('\u{FFFD}'),
            "decoded name {:?} contains U+FFFD — decode is not injective",
            name
        );
    }
}

#[test]
fn stream_reader_decodes_sjis_names_from_local_headers() {
    // The streaming reader parses local file headers (not the central
    // directory), so this exercises the LocalFileHeader decode path.
    let mut stream = ZipStreamReader::new(Cursor::new(ZIP_SJIS_NO_EFS));
    let mut seen = Vec::new();
    while let Some(mut entry) = stream.next_entry().expect("stream must parse") {
        let name = entry.meta.name.clone();
        let mut data = Vec::new();
        entry.read_to_end(&mut data).expect("entry read");
        seen.push((name, data));
    }
    assert_eq!(seen.len(), 2);
    assert_eq!(seen[0].0, "あ.txt");
    assert_eq!(seen[0].1, b"HIRAGANA-A");
    assert_eq!(seen[1].0, "い.txt");
    assert_eq!(seen[1].1, b"HIRAGANA-I");
}

#[test]
fn ascii_names_still_roundtrip_through_writer_and_reader() {
    // Guard against regressions in the common ASCII path.
    let mut bytes = Vec::new();
    {
        let mut writer = oxiarc_archive::zip::ZipWriter::new(&mut bytes);
        writer
            .add_file("plain.txt", b"plain body")
            .expect("add_file");
        writer.finish().expect("finish");
    }
    let mut reader = ZipReader::new(Cursor::new(bytes)).expect("roundtrip must parse");
    let entry = reader.entries()[0].clone();
    assert_eq!(entry.name, "plain.txt");
    assert_eq!(reader.entry_name_bytes(0), Some(b"plain.txt".as_slice()));
    let data = reader.extract(&entry).expect("extract");
    assert_eq!(data, b"plain body");
}
