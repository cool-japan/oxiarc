//! Hermetic tests for ZIP entry-name decoding (EFS / Shift_JIS / CP437).
//!
//! Regression tests for the data-loss bug where non-EFS Shift_JIS entry
//! names (the norm for Japanese-Windows ZIPs) were decoded with
//! `String::from_utf8_lossy`, collapsing distinct names such as `あ.txt`
//! and `い.txt` into identical U+FFFD strings so extraction silently
//! overwrote files.
//!
//! The fixtures below were generated ONCE during development with a
//! python3 (stdlib-only) script and verified with both `zipfile`
//! (CRC check via `ZipFile.testzip`) and `bsdtar -tvf`; the byte arrays
//! are embedded here so the committed test suite never invokes external
//! tools. Every fixture holds two stored-method entries whose raw names
//! differ only in bytes that a lossy UTF-8 decode would destroy.

