/// XZ stream header for CRC32 check type.
fn xz_stream_header() -> Vec<u8> {
    let mut out = vec![0xFD, 0x37, 0x7A, 0x58, 0x5A, 0x00];
    let flags = [0x00, 0x01]; // check type: CRC32
    out.extend_from_slice(&flags);
    out.extend_from_slice(&Crc32::compute(&flags).to_le_bytes());
    out
}

/// Assemble a block header from its body: size byte + body + padding +
/// valid CRC32, exactly as the xz spec lays it out.
fn xz_block_header(body: &[u8]) -> Vec<u8> {
    let header_size_byte = ((body.len() + 4) / 4) as u8;
    let total = (header_size_byte as usize + 1) * 4;
    let padding = total - 1 - body.len() - 4;

    let mut padded = body.to_vec();
    padded.resize(body.len() + padding, 0x00);

    let mut crc_input = Vec::with_capacity(1 + padded.len());
    crc_input.push(header_size_byte);
    crc_input.extend_from_slice(&padded);
    let crc = Crc32::compute(&crc_input);

    let mut out = Vec::with_capacity(total);
    out.push(header_size_byte);
    out.extend_from_slice(&padded);
    out.extend_from_slice(&crc.to_le_bytes());
    out
}

/// Encode an xz-style multibyte integer.
fn xz_varint(mut value: u64) -> Vec<u8> {
    let mut out = Vec::new();
    loop {
        let byte = (value & 0x7F) as u8;
        value >>= 7;
        if value == 0 {
            out.push(byte);
            break;
        }
        out.push(byte | 0x80);
    }
    out
}

#[test]
fn xz_huge_declared_compressed_size_errors_without_abort() {
    // XZ-01: block header declares compressed_size = 2^60. The old code
    // did `vec![0u8; compressed_size]` and aborted the process with an
    // allocation failure; it must now return Err.
    let mut body = vec![0x40]; // flags: 1 filter, has compressed size
    body.extend_from_slice(&xz_varint(1u64 << 60));
    body.extend_from_slice(&[0x21, 0x01, 0x00]); // LZMA2 filter, 1 prop byte

    let mut stream = xz_stream_header();
    stream.extend_from_slice(&xz_block_header(&body));

    let result = xz::decompress(&mut Cursor::new(&stream));
    assert!(result.is_err(), "huge declared size must be rejected");
}

#[test]
fn xz_filter_props_overrunning_header_errors_without_panic() {
    // XZ-02: the LZMA2 filter declares 127 property bytes but the header
    // body ends long before that. The old code indexed `header[offset]`
    // unchecked; it must now return Err.
    let body = vec![0x00, 0x21, 0x7F]; // flags: 1 filter; LZMA2; props = 127
    let mut stream = xz_stream_header();
    stream.extend_from_slice(&xz_block_header(&body));

    let result = xz::decompress(&mut Cursor::new(&stream));
    assert!(result.is_err(), "overrunning filter props must be rejected");
}

#[test]
fn xz_truncated_props_varint_errors_without_panic() {
    // XZ-02 (varint shape): the props-size varint has its continuation
    // bit set on the final body byte, so parsing runs off the end.
    let body = vec![0x00, 0x21, 0x80]; // flags: 1 filter; LZMA2; truncated varint
    let mut stream = xz_stream_header();
    stream.extend_from_slice(&xz_block_header(&body));

    let result = xz::decompress(&mut Cursor::new(&stream));
    assert!(result.is_err(), "truncated props varint must be rejected");
}

#[test]
fn xz_block_header_bitflip_rejected_by_crc() {
    // XZ-03: any bit flip inside the block header (here: the filter-id
    // byte) must be caught by the now-validated header CRC32.
    let original = b"xz block header CRC must be validated".to_vec();
    let mut compressed = xz::compress(&original, 6).expect("compress");

    // Stream header is 12 bytes; byte 12 is the block-header size byte,
    // byte 13 the first body byte. Flip a body byte without fixing the CRC.
    compressed[14] ^= 0x10;

    let result = xz::decompress(&mut Cursor::new(&compressed));
    assert!(
        result.is_err(),
        "corrupted block header must be rejected before use"
    );
}

// =========================================================================
// Multi-chunk XZ (real `xz -6` output) at the archive level
// =========================================================================

/// The fixture was produced by XZ Utils (`xz -6`) from 128 KiB of
/// deterministic data: 2048 alternating 64-byte blocks — even blocks from
/// the xorshift64 stream below, odd blocks a fixed text pattern. Its single
/// block spans two LZMA2 chunks (61 KiB + 6 KiB compressed), the second
/// with control byte 0x80 (no state/dictionary reset), which requires the
/// decoder's persistent uncompressed position to resolve back-references.
const MULTICHUNK_XZ: &[u8] = include_bytes!("data/xz_multichunk_xz6.xz");

fn xorshift_stream(seed: u64, len: usize) -> Vec<u8> {
    let mut state = seed | 1;
    let mut out = Vec::with_capacity(len + 8);
    while out.len() < len {
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        out.extend_from_slice(&state.to_le_bytes());
    }
    out.truncate(len);
    out
}

fn multichunk_plaintext() -> Vec<u8> {
    let pattern: Vec<u8> = b"OxiArc multi-chunk XZ interop fixture block. "
        .iter()
        .cycle()
        .take(64)
        .copied()
        .collect();
    let prng = xorshift_stream(0x0A2C_57F3_11D4_B689, 64 * 1024);
    let mut data = Vec::with_capacity(128 * 1024);
    let mut prng_off = 0;
    for i in 0..2048 {
        if i % 2 == 0 {
            data.extend_from_slice(&prng[prng_off..prng_off + 64]);
            prng_off += 64;
        } else {
            data.extend_from_slice(&pattern);
        }
    }
    data
}

#[test]
fn xz_real_cli_multichunk_block_decodes_byte_exact() {
    let expected = multichunk_plaintext();
    assert_eq!(expected.len(), 128 * 1024);

    let decoded = xz::decompress(&mut Cursor::new(MULTICHUNK_XZ))
        .expect("decode real xz -6 multi-chunk stream");
    assert_eq!(decoded.len(), expected.len(), "decoded length mismatch");
    assert_eq!(decoded, expected, "decoded bytes mismatch");
}

