const SEVENZ_MAGIC: [u8; 6] = [0x37, 0x7A, 0xBC, 0xAF, 0x27, 0x1C];

/// Wrap raw next-header bytes in a valid 32-byte 7z signature header
/// (correct start-header and next-header CRC32s) so parsing reaches the
/// header body under test.
fn sevenz_archive(header: &[u8]) -> Vec<u8> {
    let mut sig = vec![0u8; 32];
    sig[0..6].copy_from_slice(&SEVENZ_MAGIC);
    sig[6] = 0; // major version
    sig[7] = 4; // minor version
    sig[12..20].copy_from_slice(&0u64.to_le_bytes()); // next header offset
    sig[20..28].copy_from_slice(&(header.len() as u64).to_le_bytes());
    sig[28..32].copy_from_slice(&Crc32::compute(header).to_le_bytes());
    let start_crc = Crc32::compute(&sig[12..32]);
    sig[8..12].copy_from_slice(&start_crc.to_le_bytes());
    sig.extend_from_slice(header);
    sig
}

/// Encode a value in the full 8-extra-byte form of a 7z variable-length
/// number (always valid, independent of magnitude).
fn sevenz_number_full(value: u64) -> Vec<u8> {
    let mut out = vec![0xFF];
    out.extend_from_slice(&value.to_le_bytes());
    out
}

#[test]
fn sevenz_unbounded_complex_coder_stream_counts_error() {
    // SEVENZ-01: a complex coder declaring 2^40 input/output streams.
    // The old code fed `total_out_streams - 1` straight into
    // `Vec::with_capacity` (capacity-overflow panic / TiB reservation).
    let mut header = vec![
        0x01, // kHeader
        0x04, // kMainStreamsInfo
        0x06, // kPackInfo
        0x00, // pack pos = 0
        0x01, // 1 pack stream
        0x09, 0x01, // kSize: [1]
        0x00, // kEnd (PackInfo)
        0x07, // kUnpackInfo
        0x0B, // kFolder
        0x01, // 1 folder
        0x00, // not external
        0x01, // 1 coder
        0x11, // codec-id size 1 | complex (0x10)
        0x00, // codec id: Copy
    ];
    header.extend_from_slice(&sevenz_number_full(1u64 << 40)); // num in streams
    header.extend_from_slice(&sevenz_number_full(1u64 << 40)); // num out streams

    let result = SevenZReader::new(Cursor::new(sevenz_archive(&header)));
    assert!(
        result.is_err(),
        "unbounded coder stream counts must be rejected"
    );
}

#[test]
fn sevenz_moderate_but_implausible_stream_counts_error() {
    // SEVENZ-01 (second shape): counts that pass the generic 16M bound
    // but exceed any real folder layout (reference limit: 64 streams).
    let mut header = vec![
        0x01, 0x04, // kHeader, kMainStreamsInfo
        0x06, 0x00, 0x01, 0x09, 0x01, 0x00, // kPackInfo {pos 0, 1 stream, size [1]}
        0x07, 0x0B, 0x01, 0x00, // kUnpackInfo, kFolder, 1 folder, internal
        0x01, 0x11, 0x00, // 1 coder, complex copy coder
    ];
    header.extend_from_slice(&sevenz_number_full(100_000)); // in streams
    header.extend_from_slice(&sevenz_number_full(100_000)); // out streams

    let result = SevenZReader::new(Cursor::new(sevenz_archive(&header)));
    assert!(
        result.is_err(),
        "implausible folder stream counts must be rejected"
    );
}

#[test]
fn sevenz_unbounded_substream_crc_aggregate_errors() {
    // SEVENZ-02: one folder claiming 16M substreams, then a kCrc block
    // with AllAreDefined = 1 and no digest bytes. The old code
    // materialized `vec![true; 16M]` (and 256 MiB for 16 such folders)
    // without consuming a single input byte; it must now Err because
    // 16M digests could never fit in the remaining header bytes.
    let mut header = vec![
        0x01, 0x04, // kHeader, kMainStreamsInfo
        0x06, 0x00, 0x01, 0x09, 0x40, 0x00, // kPackInfo {pos 0, 1 stream, size [64]}
        0x07, // kUnpackInfo
        0x0B, 0x01, 0x00, // kFolder, 1 folder, internal
        0x01, 0x01, 0x00, // 1 coder: simple Copy
        0x0C, 0x40, // kCodersUnpackSize: [64]
        0x00, // kEnd (UnpackInfo)
        0x08, // kSubStreamsInfo
        0x0D, // kNumUnpackStream
    ];
    header.extend_from_slice(&sevenz_number_full(16 * 1024 * 1024)); // 16M substreams
    header.push(0x0A); // kCrc
    header.push(0x01); // AllAreDefined = 1, no digest bytes follow

    let result = SevenZReader::new(Cursor::new(sevenz_archive(&header)));
    assert!(
        result.is_err(),
        "unbounded substream CRC aggregate must be rejected"
    );
}

#[test]
fn sevenz_multi_folder_substream_sum_overflow_errors() {
    // SEVENZ-02 (aggregate-across-folders shape): 16 folders x 16M
    // substreams each — every per-folder count is individually within the
    // 16M bound, but the 256M aggregate must be rejected.
    let mut header = vec![
        0x01, 0x04, // kHeader, kMainStreamsInfo
        0x06, 0x00, 0x10, // kPackInfo: pos 0, 16 pack streams
        0x09, // kSize
    ];
    header.extend_from_slice(&[0x01; 16]); // 16 pack sizes of 1
    header.push(0x00); // kEnd (PackInfo)
    header.extend_from_slice(&[0x07, 0x0B, 0x10, 0x00]); // kUnpackInfo, kFolder, 16, internal
    for _ in 0..16 {
        header.extend_from_slice(&[0x01, 0x01, 0x00]); // simple Copy coder
    }
    header.push(0x0C); // kCodersUnpackSize
    header.extend_from_slice(&[0x40; 16]); // 16 unpack sizes of 64
    header.push(0x00); // kEnd (UnpackInfo)
    header.extend_from_slice(&[0x08, 0x0D]); // kSubStreamsInfo, kNumUnpackStream
    for _ in 0..16 {
        header.extend_from_slice(&sevenz_number_full(16 * 1024 * 1024));
    }
    header.push(0x0A); // kCrc
    header.push(0x01); // AllAreDefined

    let result = SevenZReader::new(Cursor::new(sevenz_archive(&header)));
    assert!(result.is_err(), "256M substream aggregate must be rejected");
}

#[test]
fn sevenz_valid_fixture_still_opens_after_hardening() {
    // Guard against over-tightening: the embedded bsdtar fixture (real
    // multi-entry archive with SubStreamsInfo CRCs) must still parse and
    // extract after the new bounds.
    let bytes: &[u8] = include_bytes!("data/sevenz_bsdtar_copy.7z");
    let mut reader = SevenZReader::new(Cursor::new(bytes)).expect("open fixture");
    let entries = reader.sevenz_entries().to_vec();
    assert_eq!(entries.len(), 5);
    let alpha = entries
        .iter()
        .position(|e| e.name == "alpha.txt")
        .expect("alpha.txt present");
    let data = reader.extract(alpha).expect("extract alpha.txt");
    assert_eq!(data, b"Hello, 7z world!\n");
}
