//! Permanent robustness gates for the ZIP / XZ / 7z readers (Wave 3).
//!
//! Every test here is hermetic (crafted byte vectors or embedded fixtures;
//! no external tools) and pins a specific hardening fix:
//!
//! * ZIP-02 — a crafted DOS date with month/day = 0 must not panic.
//! * XZ-01  — a block header declaring a huge compressed size must `Err`
//!   instead of aborting the process on allocation.
//! * XZ-02  — filter properties overrunning the block header must `Err`
//!   instead of indexing out of bounds.
//! * XZ-03  — a corrupted block header must be rejected by its CRC32
//!   before any parsed field is trusted.
//! * SEVENZ-01 — unbounded complex-coder stream counts must `Err` instead
//!   of a capacity-overflow panic / TiB reservation.
//! * SEVENZ-02 — an unbounded SubStreamsInfo `kCrc` aggregate must `Err`
//!   instead of reserving hundreds of MiB from a ~200-byte header.
//! * Multi-chunk XZ — a real `xz -6` stream whose block spans several
//!   LZMA2 chunks must decode byte-exactly at the archive level
//!   (embedded fixture generated by XZ Utils).

use oxiarc_archive::sevenz::SevenZReader;
use oxiarc_archive::xz;
use oxiarc_archive::zip::{ZipReader, ZipWriter};
use oxiarc_core::Crc32;
use std::io::Cursor;

// =========================================================================
// ZIP-02: month-0 / day-0 DOS date must not panic
// =========================================================================

/// Locate `sig` in `haystack` and return the offset after it.
fn find_sig(haystack: &[u8], sig: &[u8]) -> usize {
    haystack
        .windows(sig.len())
        .position(|w| w == sig)
        .expect("signature not found in crafted archive")
}

#[test]
fn zip_month_zero_dos_date_does_not_panic() {
    // Build a normal one-file archive, then zero out the DOS time/date
    // words in both the local and the central-directory headers — the
    // shape produced by the fuzzer that previously panicked with
    // "attempt to subtract with overflow" in read_central_dir_entry.
    let mut bytes = Vec::new();
    {
        let mut writer = ZipWriter::new(&mut bytes);
        writer
            .add_file("clock.txt", b"time flies like an arrow")
            .expect("add_file");
        writer.finish().expect("finish");
    }

    // Local file header: mtime at +10, mdate at +12 from the signature.
    let local = find_sig(&bytes, &[0x50, 0x4B, 0x03, 0x04]);
    for b in &mut bytes[local + 10..local + 14] {
        *b = 0;
    }
    // Central directory header: mtime at +12, mdate at +14.
    let central = find_sig(&bytes, &[0x50, 0x4B, 0x01, 0x02]);
    for b in &mut bytes[central + 12..central + 16] {
        *b = 0;
    }

    // Opening must not panic, the timestamp must be usable, and the
    // payload (whose CRC is untouched) must still extract byte-exactly.
    let mut reader = ZipReader::new(Cursor::new(&bytes)).expect("open crafted zip");
    let entry = reader.entries()[0].clone();
    let modified = entry.modified.expect("modified timestamp present");
    assert!(modified >= std::time::UNIX_EPOCH);
    let data = reader.extract(&entry).expect("extract");
    assert_eq!(data, b"time flies like an arrow");
}

